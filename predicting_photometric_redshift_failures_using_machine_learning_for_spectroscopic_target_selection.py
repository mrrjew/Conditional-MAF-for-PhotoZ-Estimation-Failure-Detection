@tf.function
def train_step(x_batch, y_batch):
    with tf.GradientTape() as tape:
        params = param_net(x_batch, training=True)

        bijector_list = []
        for i in range(NUM_MAF_LAYERS):
            loc_i       = tf.squeeze(params[2 * i],     axis=-1)
